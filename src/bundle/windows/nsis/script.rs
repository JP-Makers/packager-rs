// Pure-Rust NSIS Modern UI 2 script and language file generator.

use crate::metadata::Metadata;
use std::collections::HashMap;

/// Generates the complete Modern UI 2 NSIS script content.
pub fn generate_nsi_script(
    metadata: &Metadata,
    staged_files: &[String],
    license_file: Option<&str>,
    icon_file: Option<&str>,
) -> String {
    let app_name = metadata.app_name();
    let version = &metadata.version;
    let manufacturer = metadata.win_manufacturer();
    let install_dir = metadata.win_install_dir();
    let exec_name = metadata.executable_name();
    let main_exe = if exec_name.ends_with(".exe") {
        exec_name
    } else {
        format!("{}.exe", exec_name)
    };

    let license_directive = match license_file {
        Some(f) => format!("!insertmacro MUI_PAGE_LICENSE \"{}\"", f),
        None => "; No license file provided".to_string(),
    };

    let icon_path = match icon_file {
        Some(ic) => format!("graphics\\{}", ic),
        None => "graphics\\icon.ico".to_string(),
    };

    let mut file_entries = String::new();
    let mut delete_entries = String::new();

    for f in staged_files {
        let win_path = f.replace('/', "\\");
        file_entries.push_str(&format!("  File \"{}\"\n", win_path));
        delete_entries.push_str(&format!("  Delete \"$INSTDIR\\{}\"\n", win_path));
    }

    format!(
r#"; NSIS Modern User Interface
; {app_name} Setup Script
; Generated by package-builder
; Copyright (C) {manufacturer}

;--------------------------------
; Include Modern UI

!include "MUI2.nsh"
!include "FileFunc.nsh"
!include "LogicLib.nsh"

;--------------------------------
; General

!ifndef VERSION
  !define VERSION "{version}"
!endif

; Name and file
Name "{app_name} v${{VERSION}} Setup"
OutFile "{name}_Setup.exe"
Unicode True

; Default installation folder
InstallDir "$PROGRAMFILES\{install_dir}"

; Get installation folder from registry if available
InstallDirRegKey HKCU "Software\{manufacturer}\{app_name}" ""

; Request application privileges
RequestExecutionLevel admin

; Compression
SetCompressor /SOLID lzma

;--------------------------------
; Interface Settings

!define MUI_ABORTWARNING
!define MUI_ICON "{icon_path}"
!define MUI_UNICON "{icon_path}"

; Header image (150x57 pixels, 24-bit BMP)
!define MUI_HEADERIMAGE
!define MUI_HEADERIMAGE_BITMAP "graphics\header.bmp"
!define MUI_HEADERIMAGE_UNBITMAP "graphics\header.bmp"

; Welcome/Finish page images
!define MUI_WELCOMEFINISHPAGE_BITMAP "graphics\wizard.bmp"
!define MUI_UNWELCOMEFINISHPAGE_BITMAP "graphics\wizard.bmp"

; Welcome page
!define MUI_WELCOMEPAGE_TITLE $(WELCOME_TITLE)
!define MUI_WELCOMEPAGE_TEXT $(WELCOME_TEXT)

; License page
!define MUI_LICENSEPAGE_TEXT_TOP $(LICENSE_TOP)
!define MUI_LICENSEPAGE_TEXT_BOTTOM $(LICENSE_BOTTOM)
!define MUI_LICENSEPAGE_BUTTON "I Agree"

; Components page
!define MUI_COMPONENTSPAGE_TEXT_TOP $(COMPONENTS_TITLE)
!define MUI_COMPONENTSPAGE_TEXT_COMPLIST $(COMPONENTS_TEXT)

; Directory page
!define MUI_DIRECTORYPAGE_TEXT_TOP $(DIRECTORY_TITLE)
!define MUI_DIRECTORYPAGE_TEXT_DESTINATION $(DIRECTORY_TEXT)

; Finish page
!define MUI_FINISHPAGE_TITLE $(FINISH_TITLE)
!define MUI_FINISHPAGE_TEXT $(FINISH_TEXT)
!define MUI_FINISHPAGE_RUN "$INSTDIR\{main_exe}"
!define MUI_FINISHPAGE_RUN_TEXT $(FINISH_RUN)

;--------------------------------
; Language Selection Dialog Settings
!define MUI_LANGDLL_ALWAYSSHOW
!define MUI_LANGDLL_REGISTRY_ROOT "HKCU"
!define MUI_LANGDLL_REGISTRY_KEY "Software\{manufacturer}\{app_name}"
!define MUI_LANGDLL_REGISTRY_VALUENAME "Installer Language"

;--------------------------------
; Pages

!insertmacro MUI_PAGE_WELCOME
{license_directive}
!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_COMPONENTS
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_PAGE_FINISH

!insertmacro MUI_UNPAGE_WELCOME
!insertmacro MUI_UNPAGE_CONFIRM
!insertmacro MUI_UNPAGE_INSTFILES
!insertmacro MUI_UNPAGE_FINISH

;--------------------------------
; Languages

!insertmacro MUI_LANGUAGE "English"
!insertmacro MUI_LANGUAGE "French"
!insertmacro MUI_LANGUAGE "German"
!insertmacro MUI_LANGUAGE "Spanish"
!insertmacro MUI_LANGUAGE "Italian"
!insertmacro MUI_LANGUAGE "Japanese"
!insertmacro MUI_LANGUAGE "SimpChinese"
!insertmacro MUI_LANGUAGE "Portuguese"

; Language files
!include "lang\English.nsh"
!include "lang\French.nsh"
!include "lang\German.nsh"
!include "lang\Spanish.nsh"
!include "lang\Italian.nsh"
!include "lang\Japanese.nsh"
!include "lang\SimpChinese.nsh"
!include "lang\Portuguese.nsh"

;--------------------------------
; Installer Sections

Section "{app_name} Application" SecMain
  SectionIn RO

  SetOutPath "$INSTDIR"

  ; Add files
{file_entries}
  ; Store installation folder
  WriteRegStr HKCU "Software\{manufacturer}\{app_name}" "" $INSTDIR

  ; Create uninstaller
  WriteUninstaller "$INSTDIR\Uninstall.exe"

  ; Register with Add/Remove Programs
  WriteRegStr HKLM "Software\Microsoft\Windows\CurrentVersion\Uninstall\{app_name}" "DisplayName" "{app_name}"
  WriteRegStr HKLM "Software\Microsoft\Windows\CurrentVersion\Uninstall\{app_name}" "DisplayVersion" "${{VERSION}}"
  WriteRegStr HKLM "Software\Microsoft\Windows\CurrentVersion\Uninstall\{app_name}" "Publisher" "{manufacturer}"
  WriteRegStr HKLM "Software\Microsoft\Windows\CurrentVersion\Uninstall\{app_name}" "UninstallString" "$INSTDIR\Uninstall.exe"
  WriteRegStr HKLM "Software\Microsoft\Windows\CurrentVersion\Uninstall\{app_name}" "InstallLocation" "$INSTDIR"
  WriteRegStr HKLM "Software\Microsoft\Windows\CurrentVersion\Uninstall\{app_name}" "DisplayIcon" "$INSTDIR\icon.ico"
  WriteRegDWORD HKLM "Software\Microsoft\Windows\CurrentVersion\Uninstall\{app_name}" "NoModify" 1
  WriteRegDWORD HKLM "Software\Microsoft\Windows\CurrentVersion\Uninstall\{app_name}" "NoRepair" 1

SectionEnd

Section "Start Menu Shortcuts" SecStartMenu
  CreateDirectory "$SMPROGRAMS\{app_name}"
  CreateShortcut "$SMPROGRAMS\{app_name}\{app_name}.lnk" "$INSTDIR\{main_exe}" "" "$INSTDIR\icon.ico"
  CreateShortcut "$SMPROGRAMS\{app_name}\Uninstall {app_name}.lnk" "$INSTDIR\Uninstall.exe" "" "$INSTDIR\icon.ico"
SectionEnd

Section "Desktop Shortcut" SecDesktop
  CreateShortcut "$DESKTOP\{app_name}.lnk" "$INSTDIR\{main_exe}" "" "$INSTDIR\icon.ico"
SectionEnd

Section "Quick Launch Shortcut" SecQuickLaunch
  CreateShortcut "$QUICKLAUNCH\{app_name}.lnk" "$INSTDIR\{main_exe}" "" "$INSTDIR\icon.ico"
SectionEnd

;--------------------------------
; Descriptions

LangString DESC_SecMain ${{LANG_ENGLISH}} "The core {app_name} application files (required)."
LangString DESC_SecMain ${{LANG_FRENCH}} "Les fichiers principaux de l'application {app_name} (requis)."
LangString DESC_SecMain ${{LANG_GERMAN}} "Die Hauptanwendungsdateien von {app_name} (erforderlich)."
LangString DESC_SecMain ${{LANG_SPANISH}} "Los archivos principales de la aplicacion {app_name} (requerido)."
LangString DESC_SecMain ${{LANG_ITALIAN}} "I file principali dell'applicazione {app_name} (richiesto)."
LangString DESC_SecMain ${{LANG_JAPANESE}} "{app_name} コアアプリケーションファイル（必須）。"
LangString DESC_SecMain ${{LANG_SIMPCHINESE}} "{app_name} 核心应用程序文件（必需）。"
LangString DESC_SecMain ${{LANG_PORTUGUESE}} "Os arquivos principais do aplicativo {app_name} (obrigatorio)."

LangString DESC_SecStartMenu ${{LANG_ENGLISH}} "Create shortcuts in the Start Menu."
LangString DESC_SecStartMenu ${{LANG_FRENCH}} "Creer des raccourcis dans le menu Demarrer."
LangString DESC_SecStartMenu ${{LANG_GERMAN}} "Verknuepfungen im Startmenue erstellen."
LangString DESC_SecStartMenu ${{LANG_SPANISH}} "Crear accesos directos en el Menu Inicio."
LangString DESC_SecStartMenu ${{LANG_ITALIAN}} "Crea collegamenti nel Menu Start."
LangString DESC_SecStartMenu ${{LANG_JAPANESE}} "スタートメニューにショートカットを作成します。"
LangString DESC_SecStartMenu ${{LANG_SIMPCHINESE}} "在开始菜单中创建快捷方式。"
LangString DESC_SecStartMenu ${{LANG_PORTUGUESE}} "Criar atalhos no Menu Iniciar."

LangString DESC_SecDesktop ${{LANG_ENGLISH}} "Create a shortcut on the Desktop."
LangString DESC_SecDesktop ${{LANG_FRENCH}} "Creer un raccourci sur le Bureau."
LangString DESC_SecDesktop ${{LANG_GERMAN}} "Verknuepfung auf dem Desktop erstellen."
LangString DESC_SecDesktop ${{LANG_SPANISH}} "Crear un acceso directo en el Escritorio."
LangString DESC_SecDesktop ${{LANG_ITALIAN}} "Crea un collegamento sul Desktop."
LangString DESC_SecDesktop ${{LANG_JAPANESE}} "デスクトップにショートカットを作成します。"
LangString DESC_SecDesktop ${{LANG_SIMPCHINESE}} "在桌面上创建快捷方式。"
LangString DESC_SecDesktop ${{LANG_PORTUGUESE}} "Criar um atalho na Area de Trabalho."

LangString DESC_SecQuickLaunch ${{LANG_ENGLISH}} "Create a shortcut in the Quick Launch toolbar."
LangString DESC_SecQuickLaunch ${{LANG_FRENCH}} "Creer un raccourci dans la barre de lancement rapide."
LangString DESC_SecQuickLaunch ${{LANG_GERMAN}} "Verknuepfung in der Schnellstartleiste erstellen."
LangString DESC_SecQuickLaunch ${{LANG_SPANISH}} "Crear un acceso directo en la barra de inicio rapido."
LangString DESC_SecQuickLaunch ${{LANG_ITALIAN}} "Crea un collegamento nella barra di Avvio rapido."
LangString DESC_SecQuickLaunch ${{LANG_JAPANESE}} "クイック起動ツールバーにショートカットを作成します。"
LangString DESC_SecQuickLaunch ${{LANG_SIMPCHINESE}} "在快速启动栏创建快捷方式。"
LangString DESC_SecQuickLaunch ${{LANG_PORTUGUESE}} "Criar um atalho na barra de Inicializacao Rapida."

; Assign language strings to sections
!insertmacro MUI_FUNCTION_DESCRIPTION_BEGIN
  !insertmacro MUI_DESCRIPTION_TEXT ${{SecMain}} $(DESC_SecMain)
  !insertmacro MUI_DESCRIPTION_TEXT ${{SecStartMenu}} $(DESC_SecStartMenu)
  !insertmacro MUI_DESCRIPTION_TEXT ${{SecDesktop}} $(DESC_SecDesktop)
  !insertmacro MUI_DESCRIPTION_TEXT ${{SecQuickLaunch}} $(DESC_SecQuickLaunch)
!insertmacro MUI_FUNCTION_DESCRIPTION_END

;--------------------------------
; Uninstaller Section

Section "Uninstall"

  ; Remove files and uninstaller
{delete_entries}
  Delete "$INSTDIR\icon.ico"
  Delete "$INSTDIR\Uninstall.exe"

  ; Remove directories used
  RMDir "$INSTDIR"

  ; Remove Start Menu launcher
  Delete "$SMPROGRAMS\{app_name}\{app_name}.lnk"
  Delete "$SMPROGRAMS\{app_name}\Uninstall {app_name}.lnk"
  RMDir "$SMPROGRAMS\{app_name}"

  ; Remove Desktop shortcut
  Delete "$DESKTOP\{app_name}.lnk"

  ; Remove Quick Launch shortcut
  Delete "$QUICKLAUNCH\{app_name}.lnk"

  ; Remove registry keys
  DeleteRegKey HKLM "Software\Microsoft\Windows\CurrentVersion\Uninstall\{app_name}"
  DeleteRegKey HKCU "Software\{manufacturer}\{app_name}"

SectionEnd

;--------------------------------
; Functions

Function .onInit
  !insertmacro MUI_LANGDLL_DISPLAY
FunctionEnd

Function un.onInit
  !insertmacro MUI_UNGETLANGUAGE
FunctionEnd
"#,
        app_name = app_name,
        name = metadata.name,
        version = version,
        manufacturer = manufacturer,
        install_dir = install_dir,
        main_exe = main_exe,
        icon_path = icon_path,
        license_directive = license_directive,
        file_entries = file_entries,
        delete_entries = delete_entries,
    )
}

